"""Results files and evals/REPORT.md."""

import json
from collections import defaultdict
from pathlib import Path

from evals.ledger import CAP
from evals.scenarios import BY_NAME, STYLE_KEYS

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "evals" / "results"
TRANSCRIPTS = RESULTS / "transcripts"
REPORT = ROOT / "evals" / "REPORT.md"
README = ROOT / "README.md"
README_MARKS = ("<!-- eval:start -->", "<!-- eval:end -->")
CATEGORIES = ("safety", "core", "adversarial")


def runs_text(runs: int, runs_for: dict[str, int]) -> str:
    """ "1 run(s) per scenario and clock", or which categories got more."""
    if not runs_for or set(runs_for.values()) == {runs}:
        return f"{runs} run(s) per scenario and clock"
    by_n: dict[int, list[str]] = defaultdict(list)
    for cat in CATEGORIES:
        by_n[runs_for.get(cat, runs)].append(cat)
    parts = [
        f"{n} run(s) on {' and '.join(cats)}" for n, cats in sorted(by_n.items(), reverse=True)
    ]
    return ", ".join(parts) + ", per scenario and clock"


def key(r: dict) -> tuple[str, str, str]:
    return r["scenario"], r["clock"], r["model"]


def tally(results: list[dict]) -> dict[tuple, tuple[int, int]]:
    """(scenario, clock, model) -> (passed, run), skipped conversations left out."""
    out: dict[tuple, list[int]] = defaultdict(lambda: [0, 0])
    for r in results:
        if r.get("skipped"):
            continue
        out[key(r)][0] += r["passed"]
        out[key(r)][1] += 1
    return {k: (p, n) for k, (p, n) in out.items()}


def transcript_text(r: dict) -> str:
    body = [
        f"# {r['scenario']} / {r['clock']} / {r['model']} / run {r['run']}",
        "PASS" if r["passed"] else "FAIL: " + "; ".join(r["failures"]),
        f"style: {r['style']}",
        f"cost: ${r['cost']:.4f}",
        "",
        *r["transcript"],
        "",
        f"bookings: {r['bookings']}",
        f"tasks: {r['tasks']}",
    ]
    return "\n".join(body) + "\n"


def write_results(meta: dict, results: list[dict]) -> Path:
    """The full run as JSON, plus each failing transcript as text."""
    RESULTS.mkdir(parents=True, exist_ok=True)
    TRANSCRIPTS.mkdir(parents=True, exist_ok=True)
    path = RESULTS / f"{meta['stamp']}-{meta['commit']}{meta.get('suffix', '')}.json"
    for r in results:
        if r.get("skipped") or r["passed"]:
            continue
        model = r["model"].split("/")[-1]
        name = f"{meta['stamp']}{meta.get('suffix', '')}-{r['scenario']}-{r['clock']}-{model}-{r['run']}.txt"
        (TRANSCRIPTS / name).write_text(transcript_text(r))
        r["transcript_file"] = f"results/transcripts/{name}"
    path.write_text(json.dumps({"meta": meta, "results": results}, indent=2, default=str) + "\n")
    return path


def compare_lines(before: list[dict], after: list[dict]) -> list[str]:
    """Before and after per scenario and clock, for every scenario either run covered."""
    b, a = tally(before), tally(after)
    lines = ["| Scenario | Clock | Model | Before | After |", "|---|---|---|---|---|"]
    for k in sorted(set(b) | set(a)):
        was = f"{b[k][0]}/{b[k][1]}" if k in b else "-"
        now = f"{a[k][0]}/{a[k][1]}" if k in a else "-"
        flag = ""
        if k in b and k in a and a[k][0] / a[k][1] < b[k][0] / b[k][1]:
            flag = " (worse)"
        lines.append(f"| {k[0]} | {k[1]} | {k[2].split('/')[-1]} | {was} | {now}{flag} |")
    return lines


def render(meta: dict, results: list[dict], ledger_total: float, changes: list[str]) -> str:
    ran = [r for r in results if not r.get("skipped")]
    skipped = [r for r in results if r.get("skipped")]
    passed = sum(r["passed"] for r in ran)
    run_cost = sum(r["cost"] for r in ran)
    per = run_cost / len(ran) if ran else 0.0
    out = [
        "# Eval report",
        "",
        (
            f"Generated by `uv run python -m evals` at {meta['started']} on commit `{meta['commit']}`. "
            f"Model {', '.join(meta['models'])}; {runs_phrase(meta['runs'])}. "
            "Regenerated on every run; the JSON behind it is "
            f"`evals/results/{meta['stamp']}-{meta['commit']}{meta.get('suffix', '')}.json`."
            + (
                f" Re-graded without model calls by the checks at `{meta['rescored_with']}`."
                if meta.get("rescored_with")
                else ""
            )
        ),
        "",
        (
            "Clocks: `demo` is Tuesday 2026-09-29 12:35 ET (office open), `night` is Monday "
            "2026-09-28 21:00 ET (office closed). Checks read the database and the transcript; there is "
            "no model judge."
        ),
        "",
        (
            f"**{passed}/{len(ran)} conversations passed.** This run cost ${run_cost:.4f} "
            f"(${per:.4f} a conversation). Ledger total ${ledger_total:.4f} of ${CAP:.2f}."
        ),
        "",
        "## By category",
        "",
        "| Category | Passed |",
        "|---|---|",
    ]
    for cat in CATEGORIES:
        mine = [r for r in ran if r["category"] == cat]
        if mine:
            out.append(f"| {cat} | {sum(r['passed'] for r in mine)}/{len(mine)} |")
    out += [
        "",
        "## By scenario",
        "",
        "| Scenario | Category | Clock | Model | Passed |",
        "|---|---|---|---|---|",
    ]
    order = {s: i for i, s in enumerate(BY_NAME)}
    for k, (p, n) in sorted(tally(ran).items(), key=lambda kv: (order[kv[0][0]], kv[0][1:])):
        cat = BY_NAME[k[0]].category
        out.append(f"| {k[0]} | {cat} | {k[1]} | {k[2].split('/')[-1]} | {p}/{n} |")
    failing = [r for r in ran if not r["passed"]]
    out += ["", "## Failures", ""]
    if not failing:
        out.append("None.")
    for r in failing:
        where = f" ([transcript]({r['transcript_file']}))" if r.get("transcript_file") else ""
        out.append(
            f"- **{r['scenario']}** / {r['clock']} / run {r['run']}{where}: "
            + "; ".join(r["failures"])
        )
    if skipped:
        out += ["", f"Skipped for budget: {len(skipped)} conversation(s)."]
    out += [
        "",
        "## Style",
        "",
        (
            "Soft naturalness counts summed over every conversation, never failures: questions bundled "
            "in one turn, home-or-business asked after the caller said it, spoken lists, and the "
            "average words in an agent turn."
        ),
        "",
        "| Model | Bundled | Re-asked type | Lists | Words a turn |",
        "|---|---|---|---|---|",
    ]
    for m in meta["models"]:
        mine = [r for r in ran if r["model"] == m]
        if not mine:
            continue
        sums = [sum(r["style"][k] for r in mine) for k in STYLE_KEYS]
        words = sum(r["style"]["words"] for r in mine) / len(mine)
        out.append(f"| {m.split('/')[-1]} | " + " | ".join(map(str, sums)) + f" | {words:.1f} |")
    if changes:
        out += ["", "## Changes", "", f"Against `{meta['compare']}`.", "", *changes]
    return "\n".join(out) + "\n"


def runs_phrase(runs: int | str) -> str:
    """Older results files hold the run count as a number."""
    return runs if isinstance(runs, str) else runs_text(runs, {})


def write_report(text: str) -> None:
    REPORT.write_text(text)


def readme_block(meta: dict, results: list[dict], before: list[dict] | None) -> str:
    """The eval table the README carries: pass rate by category, then every scenario, against the
    run given as --compare when there is one."""
    ran = [r for r in results if not r.get("skipped")]
    was = [r for r in before or [] if not r.get("skipped")]
    passed = sum(r["passed"] for r in ran)

    def rate(rs: list[dict]) -> str:
        return f"{sum(r['passed'] for r in rs)}/{len(rs)}" if rs else "-"

    out = [
        (
            f"**{passed}/{len(ran)} simulated calls passed** on commit `{meta['commit']}` "
            f"({', '.join(m.split('/')[-1] for m in meta['models'])}, {runs_phrase(meta['runs'])}). "
            "Generated by `uv run python -m evals`; detail and failures in "
            "[`evals/REPORT.md`](evals/REPORT.md)."
        ),
        "",
    ]
    if was:
        out += ["| Category | Baseline | Final |", "|---|---|---|"]
        for cat in CATEGORIES:
            out.append(
                f"| {cat} | {rate([r for r in was if r['category'] == cat])} "
                f"| {rate([r for r in ran if r['category'] == cat])} |"
            )
        out += [
            "",
            (
                f"Baseline: `{Path(meta['compare']).name}`, {len({r['scenario'] for r in was})} "
                "scenarios in the earlier run, graded by the checks of that time. Several "
                "checks are stricter now, so a baseline pass is not a pass today. A dash means the "
                "scenario did not exist yet."
            ),
        ]
    b, a = tally(was), tally(ran)
    order = {s: i for i, s in enumerate(BY_NAME)}
    out += [
        "",
        "<details><summary>Every scenario</summary>",
        "",
        "| Scenario | Category | Clock | Baseline | Final |",
        "|---|---|---|---|---|",
    ]
    for k in sorted(a, key=lambda k: (CATEGORIES.index(BY_NAME[k[0]].category), order[k[0]], k[1])):
        before_k = f"{b[k][0]}/{b[k][1]}" if k in b else "-"
        out.append(
            f"| {k[0]} | {BY_NAME[k[0]].category} | {k[1]} | {before_k} | {a[k][0]}/{a[k][1]} |"
        )
    out += ["", "</details>"]
    return "\n".join(out)


def write_readme(meta: dict, results: list[dict], before: list[dict] | None) -> bool:
    """Replace the README's eval table, between its markers, when this run covered every
    scenario. A partial run leaves it alone."""
    if set(meta["scenarios"]) != set(BY_NAME) or not README.exists():
        return False
    text = README.read_text()
    start, end = README_MARKS
    if start not in text or end not in text:
        return False
    head, rest = text.split(start, 1)
    _, tail = rest.split(end, 1)
    README.write_text(f"{head}{start}\n{readme_block(meta, results, before)}\n{end}{tail}")
    return True
